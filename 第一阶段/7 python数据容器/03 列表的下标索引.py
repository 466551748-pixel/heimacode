"""
 如何从列表中取出特定位置的数据呢？
    我们可以使用：下标索引
 语法： 列表[下标索引]
    正向索引：0 1 2 3...
    反向索引：...-3 -2 -1
"""
my_list = [1,2,3,4,5,6,7,8,9]
print(f"{my_list[0]} {my_list[1]} {my_list[2]}")
print(f"正向0:\t{my_list[0]} ")
print(f"反向-9:\t{my_list[-9]} ")

# 嵌套列表的下标
my_list2 = [[1,2,3],[4,5,6]]
# [0]:外层列表下标 [1]:内层列表下标
print(my_list2[0][1]) # 2
