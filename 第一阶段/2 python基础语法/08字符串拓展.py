"""
 字符串的多种定义法
    1.单引号定义法：name = '庄严'
    2.双引号定义法：name = "庄严"
    3.三引号定义法：name = """ """ 
    3.：与多行注释写法一样，同样支持换行操作，使用变量接收它，它就是字符串，不接收就是多行注释
"""
name = '庄严'
print(type(name))
"""
 如果想要定义字符串本身，包含单、双引号，如何写？
    1.单引号定义法，可以包含双引号
    2.双引号定义法，可以包含单引号
    3.可以使用转义字符\来将引号解除效用，变成普通字符串
"""
name = '"庄严"' # 1
print(name)
name = "'庄严'" # 2
print(name)
name = "\"庄严\"" # 3
print(name)