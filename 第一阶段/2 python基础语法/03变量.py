"""
变量：在程序运行时，能储存计算结果或者能表示值的抽象概念，就是在程序运行时，记录数据用的
定义：变量名称 = 变量的值
"""
# 定义一个变量，来记录钱包的余额
money = 100
# 通过print语句，输出变量记录的内容
print("钱包还有",money) # print(内容1,内容2,.....)

# 买了一个冰淇淋，花费10元
money = money - 10
print("买了冰淇淋还剩余",money)

# 假设每隔一个小时，输出一下钱包余额
print("现在是下午1点，钱包余额剩余：",money)
print("现在是下午2点，钱包余额剩余：",money)
print("现在是下午3点，钱包余额剩余：",money)
print("现在是下午4点，钱包余额剩余：",money)