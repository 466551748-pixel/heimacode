"""
 字符串格式化：
    1.%s：是万能占位符，任何类型都能进，进去后转为字符串
    2.%d：要求传入整数，转为字符串放入
    3.%f：要求传入数字，转为字符串放入
"""
name = "庄严"
phone_number = 13430799698
address = "shenzhen"
all = "%s是帅哥"%name
all2 = "%s的电话是%d,住址是%s"%(name,phone_number,address)# 多个%s要在括号对应好位置
"""
 all2:% 字符串格式化的结果永远是字符串！%d 只是要求传入整数，但输出整体是 str 类型。
      %d 就是把整数转为字符串格式，放入整个字符串中！
 %d：（整数占位）
 %s:（字符串占位）我先占个位置，等会有个变量过来，我把它按字符串格式放到占位的位置输出
    %:表示我要占位
    s:将变量放入占位的地方
"""
print(all)
print(all2)