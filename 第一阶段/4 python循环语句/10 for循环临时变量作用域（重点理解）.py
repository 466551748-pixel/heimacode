"""
 for i in range(5):
    print(i)
 print(i)
 思考：第二个print语句能否访问到变量i
 解答：当前写法规范上是不允许的，但是实际上可以运行的
    临时变量，在编程规范上，作用范围（作用域），只限定在for循环内部
    如果在for循环外部访问临时变量：
        实际上是可以访问到的，但是在编程规范上，是不允许，不建议的
    总的来说是一种规范限制，而非强制性限制，人为的要求，遵守规范，成为优雅的程序员
"""
i = 0 # 为了用for内临时变量i，在for循环外先定义好i，这样就符合规范，显得代码高级
for i in range(5):
    print(i)
print(i)