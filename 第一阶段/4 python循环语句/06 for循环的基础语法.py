"""
 while循环的循环条件是自定义的，自行控制循环条件
 for循环是一种“轮询”机制，是对一批内容进行“逐个处理”，将代办事项逐个完成，如洗碗一个个洗干净
 for的语法：
 for 临时变量 in 待处理数据集:
    循环满足条件时执行的代码
 1.for循环也称之为“遍历循环”
 2.同while循环不同，for循环是无法定义循环条件的，只能被动的从待处理数据集取出数据处理
 3.循环多少次完全取决于待处理的数据集，理论上for循环无法构建无限循环（被处理的数据集不可能无限大）

"""
name = "zhuangyan"
for i in name:
    # 将name的内容，挨个取出赋予x临时变量
    # 就可以在循环体内对x进行处理
    print(i)